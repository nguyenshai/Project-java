-- =====================================================================================================
-- ChatApp (RushDL - 13) - PostgreSQL schema, Version 1 (used unchanged by Version 2)
--
-- Run on an existing, empty or previous ChatApp database (PostgreSQL 17):
--   psql -v ON_ERROR_STOP=1 -d chatapp -f create_database.sql
-- The script is rerunnable: it drops every ChatApp table first, so ALL DATA IS LOST.
-- Sample data: sample_data.sql (run after this file).
--
-- Conventions
--   * Names are snake_case versions of the ERD names (UserAccount.fullName -> user_account.full_name).
--   * Ids are identity columns; times are timestamptz and the database time zone is Asia/Ho_Chi_Minh,
--     so a "year" in the reports runs from 1 January 00:00 local time to the next 1 January.
--   * Value lists are varchar + CHECK (simple to bind with JDBC setString).
--   * Accounts are never physically deleted: status DELETED + deleted_at (soft delete), so every
--     foreign key to user_account is RESTRICT. CASCADE is used only for rows that mean nothing alone.
--   * Business rules that depend on other rows (locks, blocks, group admin rights, key rotation) are
--     checked by the server; the constraints here keep the data itself consistent.
-- =====================================================================================================

BEGIN;

SET TIME ZONE 'Asia/Ho_Chi_Minh';

-- Default for new sessions. The JDBC driver sends the JVM time zone when it connects, which overrides this,
-- so the server must also run SET TIME ZONE 'Asia/Ho_Chi_Minh' on every connection it opens.
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET timezone TO %L', current_database(), 'Asia/Ho_Chi_Minh');
END
$$;

-- Trigram indexes for "contains" searches on names and chat history (trusted extension).
CREATE EXTENSION IF NOT EXISTS pg_trgm;

DROP TABLE IF EXISTS account_lock_log, group_event, group_key_share, user_key, app_open_event, login_history,
    spam_report, hidden_message, message, group_key, conversation_member, conversation, user_block, friendship,
    friend_request, user_account CASCADE;

-- -----------------------------------------------------------------------------------------------------
-- Accounts (F01-F05, F13)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE user_account (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(30)  NOT NULL CHECK (username ~ '^[A-Za-z0-9._]{3,30}$'),
    password_hash varchar(255) NOT NULL CHECK (password_hash LIKE 'pbkdf2$%'),
    full_name     varchar(100) NOT NULL CHECK (btrim(full_name) <> ''),
    address       varchar(255),
    birth_date    date         CHECK (birth_date >= DATE '1900-01-01'),
    gender        varchar(10)  NOT NULL CHECK (gender IN ('Male', 'Female', 'Other')),
    email         varchar(254) NOT NULL CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    system_role   varchar(10)  NOT NULL DEFAULT 'USER'   CHECK (system_role IN ('ADMIN', 'USER')),
    status        varchar(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'LOCKED', 'DELETED')),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    deleted_at    timestamptz,
    CONSTRAINT user_account_deleted_ck CHECK ((status = 'DELETED') = (deleted_at IS NOT NULL)),
    CONSTRAINT user_account_deleted_after_created_ck CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);
-- Usernames and emails are unique without regard to case among accounts that are not deleted.
CREATE UNIQUE INDEX user_account_username_uk ON user_account (lower(username)) WHERE status <> 'DELETED';
CREATE UNIQUE INDEX user_account_email_uk    ON user_account (lower(email))    WHERE status <> 'DELETED';
CREATE INDEX user_account_created_at_ix      ON user_account (created_at);
CREATE INDEX user_account_username_trgm_ix   ON user_account USING gin (lower(username) gin_trgm_ops);
CREATE INDEX user_account_full_name_trgm_ix  ON user_account USING gin (lower(full_name) gin_trgm_ops);

-- -----------------------------------------------------------------------------------------------------
-- Friends, requests and blocks (F06-F09, F19)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE friend_request (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id    bigint      NOT NULL REFERENCES user_account (id),
    receiver_id  bigint      NOT NULL REFERENCES user_account (id),
    status       varchar(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED')),
    created_at   timestamptz NOT NULL DEFAULT now(),
    responded_at timestamptz,
    CONSTRAINT friend_request_not_self_ck CHECK (sender_id <> receiver_id),
    CONSTRAINT friend_request_responded_ck CHECK ((status = 'PENDING') = (responded_at IS NULL)),
    CONSTRAINT friend_request_responded_after_ck CHECK (responded_at IS NULL OR responded_at >= created_at)
);
-- At most one open request between two people, whichever direction it goes.
CREATE UNIQUE INDEX friend_request_pending_pair_uk
    ON friend_request (least(sender_id, receiver_id), greatest(sender_id, receiver_id)) WHERE status = 'PENDING';
CREATE INDEX friend_request_receiver_ix ON friend_request (receiver_id, status);
CREATE INDEX friend_request_sender_ix   ON friend_request (sender_id, status);

CREATE TABLE friendship (
    user_id1   bigint      NOT NULL REFERENCES user_account (id),
    user_id2   bigint      NOT NULL REFERENCES user_account (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id1, user_id2),
    -- One row per pair: the smaller id always comes first.
    CONSTRAINT friendship_ordered_ck CHECK (user_id1 < user_id2)
);
CREATE INDEX friendship_user_id2_ix ON friendship (user_id2);

CREATE TABLE user_block (
    blocker_id      bigint      NOT NULL REFERENCES user_account (id),
    blocked_user_id bigint      NOT NULL REFERENCES user_account (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_user_id),
    CONSTRAINT user_block_not_self_ck CHECK (blocker_id <> blocked_user_id)
);
CREATE INDEX user_block_blocked_ix ON user_block (blocked_user_id);

-- -----------------------------------------------------------------------------------------------------
-- Conversations, members, messages (F11, F12, F15)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE conversation (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         varchar(10)  NOT NULL CHECK (type IN ('PRIVATE', 'GROUP')),
    group_name   varchar(100) CHECK (btrim(group_name) <> ''),
    creator_id   bigint       NOT NULL REFERENCES user_account (id),
    is_encrypted boolean      NOT NULL DEFAULT false,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT conversation_group_name_ck CHECK ((type = 'GROUP') = (group_name IS NOT NULL)),
    CONSTRAINT conversation_encrypted_group_ck CHECK (type = 'GROUP' OR NOT is_encrypted)
);
CREATE INDEX conversation_created_at_ix      ON conversation (created_at);
CREATE INDEX conversation_group_name_trgm_ix ON conversation USING gin (lower(group_name) gin_trgm_ops);

CREATE TABLE conversation_member (
    conversation_id    bigint      NOT NULL REFERENCES conversation (id),
    user_id            bigint      NOT NULL REFERENCES user_account (id),
    member_role        varchar(10) NOT NULL DEFAULT 'MEMBER' CHECK (member_role IN ('ADMIN', 'MEMBER')),
    joined_at          timestamptz NOT NULL DEFAULT now(),
    left_at            timestamptz,
    history_cleared_at timestamptz,
    PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT conversation_member_left_ck CHECK (left_at IS NULL OR left_at >= joined_at)
);
CREATE INDEX conversation_member_user_ix ON conversation_member (user_id);

-- Versioned AES group keys of an encrypted group (F12g). Only wrapped copies ever reach the server.
CREATE TABLE group_key (
    conversation_id bigint      NOT NULL REFERENCES conversation (id),
    key_version     integer     NOT NULL CHECK (key_version >= 1),
    created_by_id   bigint      NOT NULL REFERENCES user_account (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (conversation_id, key_version)
);

CREATE TABLE message (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint      NOT NULL REFERENCES conversation (id),
    sender_id       bigint      NOT NULL,
    content         text        NOT NULL CHECK (content <> ''),
    key_version     integer,
    sent_at         timestamptz NOT NULL DEFAULT now(),
    delivered_at    timestamptz,
    -- The sender must have a membership row in the conversation.
    CONSTRAINT message_sender_fk FOREIGN KEY (conversation_id, sender_id)
        REFERENCES conversation_member (conversation_id, user_id),
    -- An encrypted message names the key version of its own group; NULL means plain text.
    CONSTRAINT message_key_fk FOREIGN KEY (conversation_id, key_version)
        REFERENCES group_key (conversation_id, key_version),
    CONSTRAINT message_delivered_ck CHECK (delivered_at IS NULL OR delivered_at >= sent_at),
    -- Lets spam_report check that the reported message was written by the reported account.
    CONSTRAINT message_id_sender_uk UNIQUE (id, sender_id)
);
CREATE INDEX message_conversation_ix ON message (conversation_id, sent_at);
CREATE INDEX message_sender_ix       ON message (sender_id, sent_at);
-- Private messages still waiting for an offline recipient (F11b). delivered_at is used for private
-- conversations only; group messages always keep it NULL, so queries join conversation.type = 'PRIVATE'.
CREATE INDEX message_waiting_ix      ON message (conversation_id) WHERE delivered_at IS NULL;
-- "Contains" search in chat history (F11f, F11g); encrypted text is searched on the client.
-- Trigram indexes are on lower(col): write searches as lower(col) LIKE '%' || lower(?) || '%' (not ILIKE).
CREATE INDEX message_content_trgm_ix ON message USING gin (lower(content) gin_trgm_ops) WHERE key_version IS NULL;

-- Messages one user removed from their own history (F11e). The server checks that the user can see the message.
CREATE TABLE hidden_message (
    user_id    bigint      NOT NULL REFERENCES user_account (id),
    message_id bigint      NOT NULL REFERENCES message (id) ON DELETE CASCADE,
    hidden_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, message_id)
);
CREATE INDEX hidden_message_message_ix ON hidden_message (message_id);

-- -----------------------------------------------------------------------------------------------------
-- Spam reports (F10, F16)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE spam_report (
    id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id      bigint      NOT NULL REFERENCES user_account (id),
    reported_user_id bigint      NOT NULL REFERENCES user_account (id),
    message_id       bigint      NOT NULL,
    reason           text        NOT NULL CHECK (btrim(reason) <> ''),
    reported_content text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT spam_report_not_self_ck CHECK (reporter_id <> reported_user_id),
    -- A user reports the same message at most once.
    CONSTRAINT spam_report_once_uk UNIQUE (reporter_id, message_id),
    -- The reported message must have been sent by the reported account.
    CONSTRAINT spam_report_message_fk FOREIGN KEY (message_id, reported_user_id)
        REFERENCES message (id, sender_id)
);
CREATE INDEX spam_report_created_at_ix ON spam_report (created_at);
CREATE INDEX spam_report_reported_ix   ON spam_report (reported_user_id, created_at);
CREATE INDEX spam_report_message_ix    ON spam_report (message_id);

-- -----------------------------------------------------------------------------------------------------
-- Sign-ins and activity (F14, F20, F21)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE login_history (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint      NOT NULL REFERENCES user_account (id),
    logged_in_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX login_history_time_ix ON login_history (logged_in_at);
CREATE INDEX login_history_user_ix ON login_history (user_id, logged_in_at);

CREATE TABLE app_open_event (
    id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   bigint      NOT NULL REFERENCES user_account (id),
    opened_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX app_open_event_time_ix ON app_open_event (opened_at);
CREATE INDEX app_open_event_user_ix ON app_open_event (user_id, opened_at);

-- -----------------------------------------------------------------------------------------------------
-- End-to-end group encryption (F12g)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE user_key (
    user_id               bigint      PRIMARY KEY REFERENCES user_account (id),
    public_key            text        NOT NULL,
    encrypted_private_key text        NOT NULL,
    key_salt              varchar(64) NOT NULL,
    created_at            timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE group_key_share (
    conversation_id bigint  NOT NULL,
    key_version     integer NOT NULL,
    user_id         bigint  NOT NULL,
    wrapped_key     text    NOT NULL,
    PRIMARY KEY (conversation_id, key_version, user_id),
    CONSTRAINT group_key_share_key_fk FOREIGN KEY (conversation_id, key_version)
        REFERENCES group_key (conversation_id, key_version) ON DELETE CASCADE,
    -- A key is only shared with someone who has a membership row in that group.
    CONSTRAINT group_key_share_member_fk FOREIGN KEY (conversation_id, user_id)
        REFERENCES conversation_member (conversation_id, user_id)
);
CREATE INDEX group_key_share_user_ix ON group_key_share (user_id);

-- -----------------------------------------------------------------------------------------------------
-- Group events and lock history (F15 Activity / Monitoring, F13c / F16d lock history)
-- -----------------------------------------------------------------------------------------------------
CREATE TABLE group_event (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id bigint       NOT NULL REFERENCES conversation (id),
    actor_id        bigint       REFERENCES user_account (id),
    target_user_id  bigint       REFERENCES user_account (id),
    type            varchar(20)  NOT NULL CHECK (type IN ('CREATED', 'RENAMED', 'MEMBER_ADDED', 'MEMBER_LEFT',
                                     'MEMBER_REMOVED', 'ROLE_CHANGED', 'ENCRYPTION_ON', 'ENCRYPTION_OFF')),
    old_value       varchar(100),
    new_value       varchar(100),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT group_event_target_ck CHECK (
        (type IN ('MEMBER_ADDED', 'MEMBER_LEFT', 'MEMBER_REMOVED', 'ROLE_CHANGED')) = (target_user_id IS NOT NULL))
);
CREATE INDEX group_event_conversation_ix ON group_event (conversation_id, created_at);

CREATE TABLE account_lock_log (
    id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint      NOT NULL REFERENCES user_account (id),
    admin_id       bigint      NOT NULL REFERENCES user_account (id),
    action         varchar(10) NOT NULL CHECK (action IN ('LOCK', 'UNLOCK')),
    reason         text,
    spam_report_id bigint      REFERENCES spam_report (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT account_lock_log_not_self_ck CHECK (user_id <> admin_id),
    CONSTRAINT account_lock_log_report_ck CHECK (spam_report_id IS NULL OR action = 'LOCK')
);
CREATE INDEX account_lock_log_user_ix ON account_lock_log (user_id, created_at);
CREATE INDEX account_lock_log_time_ix ON account_lock_log (created_at);

-- -----------------------------------------------------------------------------------------------------
-- Documentation inside the database
-- -----------------------------------------------------------------------------------------------------
COMMENT ON TABLE user_account        IS 'Admin and User accounts; status DELETED is a soft delete.';
COMMENT ON COLUMN user_account.password_hash IS 'pbkdf2$<iterations>$<saltBase64>$<hashBase64>, PBKDF2WithHmacSHA256, 256-bit hash.';
COMMENT ON TABLE friend_request      IS 'Friend requests and their answers (F06b, F07).';
COMMENT ON TABLE friendship          IS 'Accepted friendships, one row per pair with user_id1 < user_id2.';
COMMENT ON TABLE user_block          IS 'Directed blocks: blocker cannot be found by or befriended by the blocked user.';
COMMENT ON TABLE conversation        IS 'Private chats (2 members) and group chats.';
COMMENT ON TABLE conversation_member IS 'Membership; left_at marks leaving or removal, history_cleared_at hides older history for that member.';
COMMENT ON TABLE group_key           IS 'Versioned AES-256 key of an encrypted group; a new version after every leave or removal.';
COMMENT ON TABLE message             IS 'Messages; key_version NULL = plain text, else Base64(IV || AES-GCM ciphertext).';
COMMENT ON TABLE hidden_message      IS 'Messages a user deleted from their own history only.';
COMMENT ON TABLE spam_report         IS 'Spam reports; reported_content is the reporter''s plain-text copy of an encrypted message.';
COMMENT ON TABLE login_history       IS 'Successful sign-ins (F14).';
COMMENT ON TABLE app_open_event      IS 'App opens, for active-user statistics (F20, F21).';
COMMENT ON TABLE user_key            IS 'RSA key pair per account; the private key is encrypted with a password-derived key on the client.';
COMMENT ON TABLE group_key_share     IS 'A group key version wrapped with one member''s RSA public key.';
COMMENT ON TABLE group_event         IS 'Group history for the Admin Activity / Monitoring tabs.';
COMMENT ON TABLE account_lock_log    IS 'Lock and unlock history; spam_report_id links a lock made from a spam report.';

COMMIT;
