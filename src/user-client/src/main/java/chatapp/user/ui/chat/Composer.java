package chatapp.user.ui.chat;

import chatapp.user.preview.PreviewServer;
import chatapp.user.ui.shared.Ui;
import javax.swing.*;
import java.awt.*;
import java.util.List;

/**
 * Message box at the bottom of a conversation: text field, Suggest and Improve (F11h, Figma C9–C10:
 * the AI panel opens above the box) and Send. Problems (empty draft, blocked person, the AI can't
 * read an encrypted group) show on a red line above the box.
 */
final class Composer extends JPanel {
    /** What the page does when a button is used; each may throw a ServiceException message via {@link #error}. */
    interface Actions {
        void send(String text);
        void suggest();
        void improve(String draft, String tone);
    }

    private enum Panel { NONE, SUGGEST, IMPROVE }

    private final Actions actions;
    private final JTextField input = Ui.field("Type a message...", 30);
    private final JPanel slot = new JPanel(new BorderLayout());
    private final JPanel buttons = new JPanel(new FlowLayout(FlowLayout.RIGHT, 8, 0));
    private final JLabel error = Ui.muted("");
    private Panel open = Panel.NONE;

    Composer(String draft, Actions actions) {
        super(new BorderLayout());
        this.actions = actions;
        setOpaque(false);
        slot.setOpaque(false);
        add(slot, BorderLayout.NORTH);
        JPanel bar = new JPanel(new BorderLayout(10, 6));
        bar.setBackground(Color.WHITE);
        bar.setBorder(BorderFactory.createCompoundBorder(BorderFactory.createMatteBorder(1, 0, 0, 0, Ui.LINE),
            BorderFactory.createEmptyBorder(12, 24, 12, 24)));
        error.setForeground(Ui.RED);
        error.setVisible(false);
        bar.add(error, BorderLayout.NORTH);
        input.setText(draft);
        input.addActionListener(e -> send());
        Ui.onText(input, () -> error.setVisible(false));
        bar.add(input, BorderLayout.CENTER);
        buttons.setOpaque(false);
        bar.add(buttons, BorderLayout.EAST);
        add(bar, BorderLayout.CENTER);
        buttons();
    }

    JTextField input() {
        return input;
    }

    String draft() {
        return input.getText();
    }

    void error(String message) {
        error.setText(message);
        error.setVisible(true);
        revalidate();
    }

    private void send() {
        actions.send(input.getText());
    }

    /** Clears the box after a message was sent. */
    void sent() {
        input.setText("");
        closePanel();
    }

    private void buttons() {
        buttons.removeAll();
        buttons.add(Ui.button("Suggest", open == Panel.SUGGEST ? Ui.Style.PRIMARY : Ui.Style.SECONDARY, "sparkles", () -> {
            if (open == Panel.SUGGEST) closePanel(); else actions.suggest();
        }));
        buttons.add(Ui.button("Improve", open == Panel.IMPROVE ? Ui.Style.PRIMARY : Ui.Style.SECONDARY, "edit", () -> {
            if (open == Panel.IMPROVE) closePanel(); else actions.improve(input.getText(), PreviewServer.TONES.getFirst());
        }));
        buttons.add(Ui.button("Send", open == Panel.NONE ? Ui.Style.PRIMARY : Ui.Style.SECONDARY, "send", this::send));
        buttons.revalidate();
        buttons.repaint();
    }

    void closePanel() {
        open = Panel.NONE;
        slot.removeAll();
        slot.setBorder(null);
        buttons();
        revalidate();
        repaint();
    }

    /** Figma C9: three reply ideas, each with Insert. */
    void showSuggestions(List<String> ideas) {
        JPanel card = aiCard("sparkles", "Suggested replies", null);
        JPanel list = Ui.column();
        for (String idea : ideas) {
            JPanel row = new JPanel(new BorderLayout(10, 0));
            row.setBackground(Ui.SOFT);
            row.setBorder(BorderFactory.createEmptyBorder(6, 12, 6, 6));
            row.add(Ui.label(idea, 13, false), BorderLayout.CENTER);
            row.add(Ui.button("Insert", () -> {
                input.setText(idea);
                closePanel();
                input.requestFocusInWindow();
            }), BorderLayout.EAST);
            row.setMaximumSize(new Dimension(Integer.MAX_VALUE, row.getPreferredSize().height));
            row.setAlignmentX(LEFT_ALIGNMENT);
            list.add(row);
            list.add(Box.createVerticalStrut(8));
        }
        JLabel note = Ui.muted("Generated by the AI assistant from the last messages. Review before sending.");
        note.setFont(note.getFont().deriveFont(12f));
        note.setAlignmentX(LEFT_ALIGNMENT);
        list.add(note);
        card.add(list);
        show(Panel.SUGGEST, card);
    }

    /** Figma C10: the draft and its rewrite in a tone, with Keep original, Try again and Replace draft. */
    void showImprove(String original, String improved, String tone) {
        JPanel tones = Ui.tabs(tone, PreviewServer.TONES.toArray(String[]::new), t -> actions.improve(original, t));
        JPanel card = aiCard("edit", "Improve message", tones);
        JPanel compare = new JPanel(new GridLayout(1, 2, 12, 0));
        compare.setOpaque(false);
        compare.add(textBox("Original", original, Ui.CANVAS));
        compare.add(textBox("Improved", improved, Ui.SELECTED));
        JPanel body = new JPanel(new BorderLayout(0, 12));
        body.setOpaque(false);
        body.add(compare);
        JPanel choices = new JPanel(new FlowLayout(FlowLayout.RIGHT, 8, 0));
        choices.setOpaque(false);
        choices.add(Ui.button("Keep original", this::closePanel));
        choices.add(Ui.button("Try again", Ui.Style.SECONDARY, "sparkles", () -> actions.improve(original, tone)));
        choices.add(Ui.button("Replace draft", Ui.Style.PRIMARY, "check", () -> {
            input.setText(improved);
            closePanel();
            input.requestFocusInWindow();
        }));
        body.add(choices, BorderLayout.SOUTH);
        card.add(body);
        show(Panel.IMPROVE, card);
    }

    private static JPanel textBox(String title, String text, Color background) {
        JPanel box = new JPanel(new BorderLayout(0, 4));
        box.setBackground(background);
        box.setBorder(BorderFactory.createEmptyBorder(9, 12, 9, 12));
        JLabel name = Ui.label(title, 12, true);
        name.setForeground(Ui.MUTED);
        box.add(name, BorderLayout.NORTH);
        box.add(Ui.paragraph(text, 13, Ui.INK, 260), BorderLayout.CENTER);
        return box;
    }

    private JPanel aiCard(String icon, String title, JComponent headerRight) {
        JPanel card = new JPanel(new BorderLayout(0, 12));
        card.setBackground(Color.WHITE);
        card.setBorder(BorderFactory.createCompoundBorder(BorderFactory.createLineBorder(Ui.BLUE),
            BorderFactory.createEmptyBorder(14, 16, 12, 16)));
        JLabel heading = Ui.label(title, 14, true);
        heading.setIcon(Ui.icon(icon, 17, Ui.BLUE));
        heading.setIconTextGap(8);
        JComponent right = headerRight;
        if (right == null) {
            JButton close = Ui.button("", Ui.Style.SECONDARY, "close", this::closePanel);
            close.setToolTipText("Close");
            close.getAccessibleContext().setAccessibleName("Close suggestions");
            right = close;
        }
        card.add(Ui.header(heading, right), BorderLayout.NORTH);
        return card;
    }

    private void show(Panel panel, JPanel card) {
        open = panel;
        error.setVisible(false);
        slot.removeAll();
        slot.setBorder(BorderFactory.createEmptyBorder(0, 24, 12, 24));
        slot.add(card);
        buttons();
        revalidate();
        repaint();
    }
}
